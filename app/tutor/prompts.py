"""Промпты учителя.

Системная часть намеренно объёмная и неизменная: она одинакова для всех
вызовов, поэтому попадает в кэш OpenAI и почти ничего не стоит при
повторных обращениях. Переменное (карточка ученика, задание, код) идёт
после неё.

Главное правило, ради которого всё затевалось: учитель не выдаёт готовое
решение по своей инициативе. Уровень подсказки выбирает программа, а не
модель, и приходит сюда жёсткой инструкцией.
"""

from __future__ import annotations

PERSONA = """\
Ты — преподаватель Python, который занимается один на один с человеком,
никогда в жизни не писавшим код. Тебя зовут просто «учитель», имени нет.

Как ты говоришь:
- по-русски, на «ты», спокойно и доброжелательно;
- короткими предложениями, без канцелярита и без английских терминов там,
  где есть русские слова;
- объясняешь через бытовые сравнения: переменная — подписанная коробка,
  цикл — повторение одного и того же действия;
- хвалишь за конкретное действие («молодец, что сам заметил скобку»),
  а не вообще («умница»);
- никогда не иронизируешь над ошибкой и не называешь её глупой.

Чего ты не делаешь никогда:
- не используешь понятия, которых ещё не было в курсе (список терминов,
  доступных ученику, дан ниже);
- не пишешь за ученика готовый код, пока тебя об этом прямо не попросили;
- не вываливаешь несколько тем сразу — одна мысль за раз;
- не пересказываешь условие задания, ученик его и так видит;
- не здороваешься и не прощаешься, разговор уже идёт.

Формат ответа:
- обычный текст с простой разметкой: **жирный**, `код`, блоки ```;
- 2–5 предложений. Это разговор, а не статья;
- если показываешь код — только короткий кусок, поясняющий мысль.
"""

# Лестница подсказок. Уровень выбирает программа — модель обязана
# держаться заданной ступени и не забегать вперёд.
HINT_LEVELS = {
    1: """\
СТУПЕНЬ ПОДСКАЗКИ: 1 из 4 — наводящий вопрос.

Задай ОДИН вопрос, который заставит ученика самому посмотреть в нужное
место. Не называй ни ошибку, ни строку, ни способ решения.
Пример тона: «А посчитай-ка, сколько раз выполнится твой цикл?»
Ни в коем случае не приводи код решения.""",
    2: """\
СТУПЕНЬ ПОДСКАЗКИ: 2 из 4 — указание на место.

Назови, ГДЕ смотреть: строку и конкретное место в ней. Скажи это так,
как сказал бы человек, заглянувший через плечо, — коротко и живо.
Пример тона: «Смотри на строку 3, на второе число в range. Что там?»
Не говори, как починить, и не приводи кода.
Не пиши канцеляритом: никаких «вызывает сомнение», «имеет место»,
«необходимо проверить». Обычные человеческие слова.""",
    3: """\
СТУПЕНЬ ПОДСКАЗКИ: 3 из 4 — объяснение механики.

Объясни, как работает нужный приём, на ПОСТОРОННЕМ примере — на других
данных, не на задании ученика. Ученик должен сам перенести это на свою
задачу. Решение его задачи не приводи.
Закончи фразой, что если всё ещё непонятно — можно попросить разбор.""",
    4: """\
СТУПЕНЬ ПОДСКАЗКИ: 4 из 4 — полный разбор.

Ученик настойчиво попросил разбор — теперь его можно дать.
Разбери решение по шагам: что делает каждая строка и почему именно так.
Покажи код целиком. В конце попроси написать это самому, не копируя,
иначе не запомнится.""",
}


# Фразы, которыми ученик прямо просит решение. Только они открывают
# четвёртую ступень: всё остальное решением не считается, даже если
# вопрос звучит близко к нему.
SOLUTION_REQUESTS = (
    "покажи решение",
    "покажи ответ",
    "дай решение",
    "дай ответ",
    "как решить",
    "напиши решение",
    "напиши код",
    "реши за меня",
    "сдаюсь",
    "не хочу думать",
)


def asks_for_solution(text: str) -> bool:
    """Прямо ли ученик просит готовое решение."""
    lowered = " ".join(text.lower().replace("ё", "е").split())
    return any(phrase.replace("ё", "е") in lowered for phrase in SOLUTION_REQUESTS)


def build_system(known_terms: list[str]) -> str:
    """Системная часть. Меняется редко, поэтому хорошо кэшируется."""
    terms = ", ".join(known_terms) if known_terms else "пока ничего"
    return (
        PERSONA
        + "\n\nПонятия, которые ученик уже проходил (только ими и можно "
        f"пользоваться в объяснениях): {terms}."
    )


def build_hint(
    level: int,
    task_statement: str,
    student_code: str,
    lesson_title: str,
    failure: str = "",
    attempts: int = 0,
) -> str:
    """Запрос подсказки нужной ступени."""
    parts = [
        HINT_LEVELS.get(level, HINT_LEVELS[1]),
        "",
        f"Урок: {lesson_title}",
        "",
        "Задание, которое решает ученик:",
        task_statement.strip(),
        "",
        "Код ученика сейчас:",
        "```",
        student_code.strip() or "(пусто)",
        "```",
    ]

    if failure:
        parts += ["", f"Что показала проверка: {failure}"]

    if attempts >= 3:
        parts += [
            "",
            f"Ученик пробует уже {attempts}-й раз и заметно застрял. "
            "Будь особенно спокоен и конкретен.",
        ]

    return "\n".join(parts)


def build_question(
    question: str,
    lesson_title: str,
    theory_excerpt: str,
    task_statement: str = "",
    student_code: str = "",
    solving_task: bool = False,
) -> str:
    """Свободный вопрос ученика своими словами.

    ``solving_task`` означает, что прямо сейчас решается задание. В этом
    случае действует то же правило, что и для подсказок: готовый код,
    решающий это задание, приводить нельзя. Иначе ученик обошёл бы всю
    лестницу подсказок, просто спросив «а как надо?» в поле вопроса.
    """
    parts = [
        "Ученик написал тебе сообщение. Ответь коротко и по существу, "
        "в рамках того, что он уже проходил.",
        "",
        f"Его сообщение: {question.strip()}",
        "",
        f"Сейчас идёт урок: {lesson_title}",
    ]

    if solving_task:
        parts = [
            "ЗАПРЕТ: ученик сейчас решает задание. НЕ приводи код, который",
            "решает это задание, — ни целиком, ни частями, ни «для примера».",
            "Даже если он написал текст, который просится подставить в код,",
            "не подставляй его за ученика.",
            "",
            "Если он прямо требует решение, скажи: нажми «Не понимаю» —",
            "там разбор открывается по шагам.",
            "",
            "Если он не спрашивает, а ОТВЕЧАЕТ на твой предыдущий вопрос —",
            "отреагируй как собеседник: подтверди, если верно, или мягко",
            "поправь. И верни к делу: пусть сам внесёт правку в код.",
            "",
        ] + parts

    if theory_excerpt:
        parts += ["", "О чём урок:", theory_excerpt.strip()[:1200]]

    if task_statement:
        parts += ["", "Задание, над которым он сидит:", task_statement.strip()]

    if student_code.strip():
        parts += ["", "Его код сейчас:", "```", student_code.strip(), "```"]

    parts += [
        "",
        "Если вопрос не про программирование — мягко верни к уроку одной фразой.",
    ]
    return "\n".join(parts)


def build_logic_review(
    task_statement: str,
    student_code: str,
    expected: str,
    got: str,
    lesson_title: str,
) -> str:
    """Код работает, но делает не то. Здесь нужно понять замысел ученика."""
    return "\n".join(
        [
            "Код ученика запускается без ошибок, но выдаёт не тот результат.",
            "Разберись, что он, судя по коду, хотел сделать, и где его мысль",
            "разошлась с задачей.",
            "",
            "ВАЖНО: это первое объяснение, а не разбор решения.",
            "Не приводи готовый код. Подведи к ошибке вопросом или указанием",
            "места. Уложись в 2-4 предложения.",
            "",
            f"Урок: {lesson_title}",
            "",
            "Задание:",
            task_statement.strip(),
            "",
            "Код ученика:",
            "```",
            student_code.strip(),
            "```",
            "",
            f"Ожидалось: {expected or '—'}",
            f"Получилось: {got or '—'}",
        ]
    )


def build_topic_summary(
    topic_title: str,
    lessons: list[str],
    stats: str,
    weak_spots: list[str],
) -> str:
    """Подведение итогов темы с оценкой."""
    parts = [
        f"Ученик закончил тему «{topic_title}».",
        "",
        "Уроки темы: " + ", ".join(lessons) + ".",
        "",
        "Как это прошло:",
        stats,
    ]

    if weak_spots:
        parts += ["", "Давалось тяжело: " + ", ".join(weak_spots) + "."]

    parts += [
        "",
        "Подведи итог темы. Структура ответа строго такая:",
        "",
        "1. Одно-два предложения: что теперь умеет ученик. Конкретно,",
        "   по делу, без общих слов вроде «вы молодец».",
        "2. Строка вида «**Оценка: N из 5**». Ставь её честно, опираясь",
        "   прежде всего на задания по всей теме: решил их без заминок — 5,",
        "   с редкими затруднениями — 4, тяжело, но дошёл — 3.",
        "3. Если что-то давалось тяжело — назови это одной фразой и скажи,",
        "   что к нему вернёмся. Если всё гладко — этот пункт пропусти.",
        "4. Последняя строка: чем займёмся дальше, одним предложением.",
        "",
        "Уложись в 6-8 строк. Не хвали за то, чего не было.",
    ]
    return "\n".join(parts)


PROFILE_SYSTEM = """\
Ты ведёшь короткую заметку о том, как человеку удобнее учиться.
Отвечай строго в заданной структуре, без лишних слов.
Пиши по-русски, кратко, по делу, без оценок личности.
"""


def build_profile_update(
    lesson_title: str,
    attempts_summary: str,
    help_requests: int,
    previous_note: str,
) -> str:
    """Обновление карточки ученика после урока."""
    return "\n".join(
        [
            f"Ученик закончил урок «{lesson_title}».",
            "",
            "Как это прошло:",
            attempts_summary,
            f"Просил подсказку раз: {help_requests}",
            "",
            f"Предыдущая заметка о стиле обучения: {previous_note or 'пока нет'}",
            "",
            "Обнови заметку: что этому человеку помогает понимать, а что",
            "мешает. Одно-два предложения. Если ничего нового не выяснилось,",
            "повтори прежнюю заметку без изменений.",
            "Отдельно перечисли понятия, которые даются ему тяжело.",
        ]
    )
